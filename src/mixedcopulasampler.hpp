// Functions to check and factorize a correlation matrix rho, i.e. to determine
// a matrix L such that rho = L·Lᵀ, so that y = L·z ~ N(0,rho) for
// z ~ N(0,I). A correlation matrix is valid when it is positive semi-definite.
namespace CorrelationMatrix {
    // Relative tolerance for the eigenvalues: eigenvalues down to
    // -sEigenvalueTolerance · (largest eigenvalue) are considered to be 0, to
    // allow for rounding errors
    constexpr double sEigenvalueTolerance { 1e-10 };

    // Message for an invalid (not positive semi-definite) correlation matrix
    constexpr QLatin1StringView sInconsistentString {
        "The correlations between the input parameters are inconsistent "
        "(the correlation matrix is not positive semi-definite)"
    };

    // Factorizes rho and returns true when rho is a valid correlation matrix.
    // The Cholesky decomposition is used when possible (positive definite
    // rho). Otherwise, e.g. for correlations of exactly -1 or 1 (positive
    // semi-definite rho), the factorization L = V·Λ^½ from the
    // eigendecomposition rho = V·Λ·Vᵀ is used. JCGM 101:2008 section 6.4.8.4
    // note 1 allows any factorization of this form.
    inline bool factorize( const Eigen::MatrixXd &rho, Eigen::MatrixXd &L ) {
        if ( rho.rows() == 0 ) {
            L = rho;
            return true;
        }

        const Eigen::LLT<Eigen::MatrixXd> llt( rho );
        if ( llt.info() == Eigen::Success ) {
            L = llt.matrixL();
            return true;
        }

        const Eigen::SelfAdjointEigenSolver<Eigen::MatrixXd> solver( rho );
        if ( solver.info() != Eigen::Success ) {
            return false;
        }
        const Eigen::VectorXd &eigenvalues { solver.eigenvalues() };  // Ascending
        const double largest { eigenvalues.maxCoeff() };
        if ( eigenvalues.minCoeff() < -sEigenvalueTolerance * largest ) {
            // Not positive semi-definite: the correlations are inconsistent
            return false;
        }
        L = solver.eigenvectors() *
            eigenvalues.cwiseMax( 0. ).cwiseSqrt().asDiagonal();
        return true;
    }

    // Returns true when rho is a valid (positive semi-definite) correlation
    // matrix
    inline bool isValid( const Eigen::MatrixXd &rho ) {
        Eigen::MatrixXd L {};
        return factorize( rho, L );
    }
}

// Template class that generates samples for correlated marginal distributions
// via inverse CDFs. Dependence is modeled in a latent normal space and mapped
// to the marginals through a Gaussian copula in getRandomSymbolValues():
//
// z ~ N(0,I) -> y = L·z ~ N(0,ρ) -> u = Φ(y) ~ Uniform -> x = F⁻¹(u) ~ Target
// independent   correlated          correlated            correlated with
// normals       normals             uniforms              correct marginals
//
// Normal variables (see addNormalVariable()) skip the mapping via the uniform
// distribution: x = mean + stdDev·y, which is exact.
//
// The independent standard normal values are generated by the class itself
// (instead of std::normal_distribution, whose algorithm and output order
// depend on the C++ standard library), so the same random seed gives the same
// samples on every platform.
//
// The RandomGenerator type must be a random number engine that returns (at
// least) 32 random bits, with the interface:
// - operator()
// - seed()
template<typename RandomGenerator>
class MixedCopulaSampler {

public:
    MixedCopulaSampler( uint32_t randomSeed = 0 )
    :   mL {},
        mY {},
        mZ {},
        mGenerator { randomSeed },
        mReady { false },
        mHasSpareNormal { false },
        mSpareNormal { 0. },
        mVariables {}
    {}


    RandomGenerator getGenerator() const {
        return mGenerator;
    }


    void addVariable( Distribution::InvCDF invCDF ) {
        mVariables.push_back( Variable { std::move( invCDF ), false, 0., 0. } );
    }


    void addNormalVariable( double mean, double stdDev ) {
        mVariables.push_back( Variable { {}, true, mean, stdDev } );
    }


    void clear(){
        mReady = false;
        mVariables.clear();
        mL = {};
        mZ.resize( 0 );
        mY.resize( 0 );
        mHasSpareNormal = false;
    }


    // Generates a sample of the variables in values. Returns false (and leaves
    // values unchanged) when the sampler is not ready, e.g. because the latent
    // correlation matrix is not valid.
    bool getRandomSymbolValues( std::vector<double> &values ) {
        if ( !canSample( values.size() ) ) {
            return false;
        }

        const size_t n { mVariables.size() };
        if ( n > 0 ) {
            // Step 1: Multivariate normal sampling via Cholesky factor
            for ( int i = 0; i < n; ++i ) {
                // Independent standard normal samples
                mZ( i ) = standardNormal();
            }
            // mL * mZ introduces correlation structure, producing correlated
            // normal samples
            mY.noalias() = mL * mZ;     // noalias() avoids temporary

            // Step 2: Mapping to actual marginals via Gaussian Copula
            for ( int i { 0 }; i < n; ++i ) {
                const Variable &variable { mVariables[ i ] };
                if ( variable.normal ) {
                    // A normal variable is directly obtained from the
                    // correlated standard normal sample
                    values[ i ] = variable.mean + variable.stdDev * mY( i );
                }
                else {
                    // Map correlated normal to uniform samples (applying any
                    // CDF to its own distribution gives a uniform
                    // distribution)
                    double u { Distribution::normalCDF( mY( i ) ) };
                    // Apply the inverse CDF of the variable distribution to
                    // produce a sample from that distribution
                    values[ i ] = variable.invCDF( u );
                }
            }
        }
        return true;
    }


    bool isReady() const {
        return mReady;
    }


    // Returns true when samples can be generated for numberOfValues values:
    // the latent correlation matrix is valid and matches the variables. These
    // conditions don't change between samples, so it is sufficient to check
    // them once before generating a series of samples.
    bool canSample( size_t numberOfValues ) const {
        const size_t n { mVariables.size() };
        return mReady &&
               static_cast<size_t>( mL.rows() ) == n &&
               numberOfValues == n;
    }


    void setGenerator( const RandomGenerator &generator ) {
        mGenerator = generator;
        mHasSpareNormal = false;
    }


    // Sets the latent correlation matrix rho and determines the factor L, such
    // that rho = L·Lᵀ (see CorrelationMatrix::factorize()). Returns false (and
    // the sampler is not ready) when rho is not a valid correlation matrix.
    bool setLatentCorrelation( const Eigen::MatrixXd &rho ) {
        mReady = CorrelationMatrix::factorize( rho, mL );
        if ( !mReady ) {
            mL = {};
            return false;
        }
        mZ.resize( mL.rows() );
        mY.resize( mL.rows() );
        return true;
    }


    void setRandomSeed( uint32_t randomSeed ) {
        mGenerator.seed( randomSeed );
        mHasSpareNormal = false;
    }


    // Returns a standard normal value using the polar method of Marsaglia. The
    // method generates 2 values at a time: the first is returned and the
    // second (the spare) is returned by the next call.
    double standardNormal() {
        if ( mHasSpareNormal ) {
            mHasSpareNormal = false;
            return mSpareNormal;
        }

        double x {};
        double y {};
        double s {};
        do {
            x = 2. * uniform() - 1.;
            y = 2. * uniform() - 1.;
            s = x * x + y * y;
        } while ( s >= 1. || s == 0. );

        const double m { std::sqrt( -2. * std::log( s ) / s ) };
        mSpareNormal = y * m;
        mHasSpareNormal = true;
        return x * m;
    }


    // Returns a uniform value in the open interval (0, 1) with 53 random bits,
    // built from 2 outputs of 32 bits of the random generator. Only exact
    // operations are used, so the value is the same on every platform.
    double uniform() {
        const uint64_t a { static_cast<uint64_t>( mGenerator() ) >> 5 };
        const uint64_t b { static_cast<uint64_t>( mGenerator() ) >> 6 };
        return ( static_cast<double>( ( a << 26 ) | b ) + 0.5 ) * 0x1.0p-53;
    }


private:
    // A variable is either sampled via its inverse CDF or, for a normal
    // variable, directly from its mean and standard deviation
    struct Variable {
        Distribution::InvCDF invCDF;
        bool normal;
        double mean;
        double stdDev;
    };

    Eigen::MatrixXd mL;
    Eigen::VectorXd mY;
    Eigen::VectorXd mZ;
    RandomGenerator mGenerator;
    bool mReady;
    bool mHasSpareNormal;
    double mSpareNormal;
    std::vector<Variable> mVariables;
};

#endif // MIXEDCOPULASAMPLER_HPP
